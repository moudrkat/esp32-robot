"""Write firmware/robot/generated/ from model/: the decode table, the on-device encoder, the prompt format, and the
robot's own headers: its inputs that are not words (cond.json) and the probes its eyes show (probes.json).
Run after retraining; the generated files are in the repo, so flashing needs only arduino-cli.

    python tools/gen_headers.py        (needs: pip install tokenizers)
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "firmware" / "robot" / "generated"
MODEL = ROOT / "model"


def main():
    GEN.mkdir(parents=True, exist_ok=True)
    tok = str(MODEL / "tokenizer.json")
    subprocess.run([sys.executable, str(ROOT / "tools" / "generate_vocab.py"), "--tokenizer", tok, "--out", str(GEN / "vocab.h")], check=True)
    subprocess.run([sys.executable, str(ROOT / "tools" / "generate_tokenizer_header.py"), "--tokenizer", tok,
                    "--out", str(GEN / "tokenizer_encoder.h")], check=True)
    (GEN / "prompt_format.h").write_text(
        '// Generated by tools/gen_headers.py: a typed request becomes "# <request>\\n", and the model writes the program\n'
        '#define PROMPT_PREFIX "# "\n#define PROMPT_SUFFIX "\\n"\n'
        '#define IDLE_TEXT "robot\\n\\ntell me what\\nto do"\n#define OLED_PROGRAM 1\n')
    c = json.loads((MODEL / "cond.json").read_text())
    v = c["vectors"]
    (GEN / "cond_vec.h").write_text(
        "// Generated by tools/gen_headers.py from model/cond.json: the model's inputs that are not words\n"
        f"#define COND_N {len(v)}\n#define COND_D {len(v[0])}\n#define COND_LAYER {c['layer']}\n"
        "static const char *COND_NAMES[COND_N] = {%s};\n" % ", ".join(f'"{n}"' for n in c["channels"])
        + "static const float COND_VEC[COND_N][COND_D] = {%s};\n" % ",\n".join("{" + ", ".join("%.7g" % x for x in r) + "}" for r in v))
    p = json.loads((MODEL / "probes.json").read_text())
    (GEN / "probe_vec.h").write_text(
        "// Generated by tools/gen_headers.py from model/probes.json: what its eyes show before it writes\n"
        f"#define PROBE_LAYER {p['layer']}\n#define PROBE_DIM {len(p['w'][0])}\n"
        "static const float PROBE_W[2][PROBE_DIM] = {%s};\n" % ",\n".join("{" + ", ".join("%.7g" % x for x in r) + "}" for r in p["w"])
        + "static const float PROBE_B[2] = {%.7g, %.7g};\n" % tuple(p["b"]))
    (GEN / "car.h").write_text(
        "// Generated by tools/gen_headers.py: what this build of the sketch is\n"
        "#define CAR_ROBOT 1\n#define CAR_COND 1\n#define LLM_STEER 1\n#define PIN_GAMMA 2\n#define CAR_PROBE 1\n#define LLM_PROBE 1\n"
        '// flash.sh writes wifi.h when you give it a Wi-Fi password; without it the robot has no Wi-Fi at all\n'
        '#if __has_include("wifi.h")\n#include "wifi.h"\n#endif\n')
    print("wrote", GEN)


if __name__ == "__main__":
    main()
